// scripts/generate-build-info.ts (2026-11-14, crash-reporting item 1) —
// writes src/lib/buildInfo.generated.ts with the current git commit hash,
// read by reportClientError() (lib/api.ts) as the "app version" field on
// every client-error report. Run automatically as part of `npm run
// publish:ota` (see package.json), BEFORE `eas update` bundles the JS, so
// every OTA publish embeds the commit it was actually built from.
//
// A trailing `*` on the hash means the working tree had uncommitted changes
// at publish time - see this project's own "Clean-branch OTA deploy
// pattern": publishing dirty means the bundle doesn't exactly match any
// single commit, which matters when correlating a crash report back to the
// code that produced it.
//
// Run: npx tsx scripts/generate-build-info.ts
import * as fs from "fs";
import * as path from "path";
import { execSync } from "child_process";

const ROOT = path.resolve(__dirname, "..");
const OUT_PATH = path.join(ROOT, "src", "lib", "buildInfo.generated.ts");

function sh(cmd: string): string {
  try {
    return execSync(cmd, { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    return "";
  }
}

function main() {
  const hash = sh("git rev-parse --short HEAD") || "unknown";
  // Untracked files (??) don't count as "dirty" for this purpose - only
  // changes to tracked files actually make the bundle disagree with the
  // commit it's nominally built from.
  const dirty = sh("git status --porcelain=v1").split("\n").some((l) => l && !l.startsWith("??"));
  const gitCommit = dirty ? `${hash}*` : hash;
  const contents = `// GENERATED by scripts/generate-build-info.ts - do not hand-edit.\n// Regenerated on every \`npm run publish:ota\`.\nexport const GIT_COMMIT = ${JSON.stringify(gitCommit)};\n`;
  fs.writeFileSync(OUT_PATH, contents);
  console.log(`generate-build-info: wrote GIT_COMMIT=${gitCommit} to ${path.relative(ROOT, OUT_PATH)}`);
}

main();
